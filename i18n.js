const normalize = (value) => value.replace(/\s+/g, " ").trim();
const originalText = new WeakMap();
const originalAttributes = new WeakMap();
const translatedAttributes = ["aria-label", "alt", "content", "placeholder", "title"];

function initialLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === "en" || saved === "es") return saved;
  } catch (_) {
    // Storage can be unavailable in private or restricted browsing contexts.
  }
  const browserLanguage = navigator.languages?.[0] || navigator.language || "en";
  return browserLanguage.toLowerCase().startsWith("es") ? "es" : "en";
}

let currentLanguage = initialLanguage();

function translateString(value, language = currentLanguage) {
  const source = normalize(value);
  return language === "es" ? (ES[source] || source) : source;
}

function translatePage(language) {
  const walker = document.createTreeWalker(
    document.documentElement,
    NodeFilter.SHOW_TEXT,
    {
      acceptNode(node) {
        const tag = node.parentElement?.tagName;
        return tag === "SCRIPT" || tag === "STYLE" || !normalize(node.nodeValue)
          ? NodeFilter.FILTER_REJECT
          : NodeFilter.FILTER_ACCEPT;
      },
    },
  );

  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    if (!originalText.has(node)) originalText.set(node, node.nodeValue);
    const source = originalText.get(node);
    const leading = source.match(/^\s*/)[0];
    const trailing = source.match(/\s*$/)[0];
    node.nodeValue = leading + translateString(source, language) + trailing;
  });

  document.querySelectorAll("*").forEach((element) => {
    if (!originalAttributes.has(element)) originalAttributes.set(element, {});
    const originals = originalAttributes.get(element);
    translatedAttributes.forEach((attribute) => {
      const value = element.getAttribute(attribute);
      if (value === null || !normalize(value)) return;
      if (!(attribute in originals)) originals[attribute] = value;
      element.setAttribute(attribute, translateString(originals[attribute], language));
    });
  });
}

function applyLanguage(language, { persist = false } = {}) {
  currentLanguage = language === "es" ? "es" : "en";
  document.documentElement.lang = currentLanguage;
  translatePage(currentLanguage);

  document.querySelectorAll("[data-language]").forEach((button) => {
    button.setAttribute("aria-pressed", String(button.dataset.language === currentLanguage));
  });

  if (persist) {
    try {
      localStorage.setItem(STORAGE_KEY, currentLanguage);
    } catch (_) {
      // The selected language still works for this page view.
    }
  }

  document.dispatchEvent(new CustomEvent("masuno:languagechange", { detail: { language: currentLanguage } }));
}

document.querySelectorAll("[data-language]").forEach((button) => {
  button.addEventListener("click", () => applyLanguage(button.dataset.language, { persist: true }));
});

window.addEventListener("storage", (event) => {
  if (event.key === STORAGE_KEY && (event.newValue === "en" || event.newValue === "es")) {
    applyLanguage(event.newValue);
  }
});

window.masUNOI18n = {
  get language() { return currentLanguage; },
  translate: (value) => translateString(value),
};

applyLanguage(currentLanguage);
